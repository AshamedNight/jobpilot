"""把「开机自启 + 每 5 分钟自愈」装进 Windows（闭环 5）。

## 两种机制，各有分工

| 机制 | 触发 | 作用 | 需要管理员？ |
|---|---|---|---|
| 启动文件夹里的 `.cmd` | 用户登录时 | 开机把服务拉起来并起跑 | 否 |
| `JobPilot-Watch` 计划任务 | 每 5 分钟 | 探活 → 挂了拉起 / pacer 停了起跑 | 否 |

为什么开机自启不用计划任务：`schtasks /sc onlogon` 在本机实测**被拒绝**（需要管理员权限）。
启动文件夹放一个 `.cmd` 不需要任何权限，效果一样，而且用户能自己看见、能自己删。

为什么不用常驻守护进程：常驻进程自己也会死。定时触发是"无状态"的——
机器重启、任务被杀，下一次触发都会自愈。

## 用法

```bash
python -m app.tools.autostart install     # 注册
python -m app.tools.autostart status      # 查看
python -m app.tools.autostart uninstall   # 卸载
```
"""

from __future__ import annotations

import os
import subprocess
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[2]
PYTHON = PROJECT_ROOT / ".venv2" / "Scripts" / "python.exe"
WATCH_TASK = "JobPilot-Watch"

STARTUP_DIR = (
    Path(os.environ.get("APPDATA", "")) / "Microsoft" / "Windows" / "Start Menu" / "Programs" / "Startup"
)
STARTUP_FILE = STARTUP_DIR / "jobpilot-start.cmd"


def _run(args: list[str]) -> tuple[int, str]:
    proc = subprocess.run(  # noqa: S603
        args, capture_output=True, text=True, encoding="gbk", errors="replace"
    )
    return proc.returncode, (proc.stdout or "") + (proc.stderr or "")


def write_startup_script() -> bool:
    """在启动文件夹写一个 .cmd（登录时自动运行）。

    内容保持**纯 ASCII**：cmd 默认代码页不是 UTF-8，写中文注释会变乱码，
    极端情况下还会把命令截断。
    """
    if not STARTUP_DIR.exists():
        return False
    body = (
        "@echo off\r\n"
        "rem jobpilot auto start (generated by app.tools.autostart)\r\n"
        f'cd /d "{PROJECT_ROOT}"\r\n'
        f'"{PYTHON}" -m app.tools.launch --detach --cap 0\r\n'
    )
    try:
        STARTUP_FILE.write_bytes(body.encode("ascii"))
        return True
    except OSError:
        return False


def remove_startup_script() -> None:
    try:
        STARTUP_FILE.unlink(missing_ok=True)
    except OSError:
        pass


def watch_command() -> str:
    return f'"{PYTHON}" -m app.tools.supervise'


def install() -> int:
    ok = True

    wrote = write_startup_script()
    print(("✅ " if wrote else "❌ ") + f"启动文件夹脚本：{STARTUP_FILE}")
    ok = ok and wrote

    args = [
        "schtasks", "/create", "/tn", WATCH_TASK,
        "/tr", f'"{watch_command()}"', "/sc", "minute", "/mo", "5", "/f",
    ]
    code, out = _run(args)
    print(("✅ " if code == 0 else "❌ ") + f"计划任务 {WATCH_TASK} → rc={code}")
    if code != 0:
        ok = False
        print("   " + out.strip()[:300])

    if ok:
        print("\n已装好：登录时自启 + 每 5 分钟自愈。")
        print(f"自愈日志：{PROJECT_ROOT / 'data' / 'supervise.log'}")
        print("注意：风控熔断中守护**不会**重启（熔断是保护，不是故障）。")
    return 0 if ok else 1


def uninstall() -> int:
    remove_startup_script()
    print(f"✅ 已删除启动脚本（若有）：{STARTUP_FILE}")

    code, out = _run(["schtasks", "/delete", "/tn", WATCH_TASK, "/f"])
    if code == 0:
        print(f"✅ 已删除计划任务 {WATCH_TASK}")
        return 0
    if "找不到" in out or "cannot find" in out.lower():
        print(f"—  计划任务 {WATCH_TASK} 本来就不存在")
        return 0
    print(f"❌ 删除计划任务失败：{out.strip()[:200]}")
    return 1


def status() -> int:
    print(("✅ " if STARTUP_FILE.exists() else "—  ") + f"启动脚本：{STARTUP_FILE}")
    code, out = _run(["schtasks", "/query", "/tn", WATCH_TASK])
    if code == 0:
        print(f"✅ 计划任务 {WATCH_TASK} 已注册")
    else:
        print(f"—  计划任务 {WATCH_TASK} 未注册")
    return 0


def main(argv: list[str] | None = None) -> int:
    action = (list(argv or sys.argv[1:]) or ["status"])[0]
    if action == "install":
        return install()
    if action == "uninstall":
        return uninstall()
    if action == "status":
        return status()
    print("用法：python -m app.tools.autostart [install|status|uninstall]")
    return 2


if __name__ == "__main__":
    raise SystemExit(main())
